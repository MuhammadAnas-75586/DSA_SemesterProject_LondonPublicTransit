    private void btnSearchZoneActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchZoneActionPerformed
        try {
            int zoneId = Integer.parseInt(txtZoneId.getText().trim());
            FareZone zone = fareZoneTree.search(zoneId);
            if (zone != null) {
                txtFareArea.setText("[SUCCESS] Fare Zone Found in BST:\n" + zone.toString() 
                    + "\n\nSample Trip (10 km): $" + String.format("%.2f", zone.calculateFare(10))
                    + "\n\n--- Full Fare Hierarchy (BST In-Order Traversal) ---\n"
                    + fareZoneTree.getInOrderTraversal());
            } else {
                txtFareArea.setText("[NOT FOUND] Zone ID " + zoneId + " does not exist in BST.");
            }
        } catch (NumberFormatException e) {
            txtFareArea.setText("[ERROR] Please enter a valid integer Zone ID.");
        }
    }//GEN-LAST:event_btnSearchZoneActionPerformed

    private void btnTapPassActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTapPassActionPerformed
        String passId = txtPassId.getText().trim();
        Commuter c = commuterRegistry.get(passId);

        if (c != null) {
            c.logTravel("Tapped at Gate [O(1) Hash Table Lookup]");
            StringBuilder sb = new StringBuilder();
            sb.append("[SUCCESS] Commuter Verified via Custom Hash Table:\n");
            sb.append(" Name: ").append(c.getName()).append("\n");
            sb.append(" Pass ID: ").append(c.getPassId()).append("\n");
            sb.append(" Balance: $").append(String.format("%.2f", c.getBalance())).append("\n\n");
            sb.append("Travel History (Doubly Linked List):\n");

            DoublyLinkedList.Node<String> curr = c.getTravelLog().getHead();
            while (curr != null) {
                sb.append(" -> ").append(curr.data).append("\n");
                curr = curr.next;
            }
            txtLogArea.setText(sb.toString());
        } else {
            txtLogArea.setText("[DENIED] Pass ID [" + passId + "] not found in Custom Hash Table.");
        }
    }//GEN-LAST:event_btnTapPassActionPerformed

